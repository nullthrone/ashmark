local wow = require("tests.helpers.wow")

describe("Core Safe", function()
  local ns, Safe
  before_each(function()
    wow.reset()
    ns = wow.load()
    Safe = ns.Safe
  end)

  describe("the secret proxy", function()
    it("raises on every operation the client forbids", function()
      local s = wow.secret("x")
      assert.has_error(function() return s .. "y" end)
      assert.has_error(function() return s < 1 end)
      assert.has_error(function() return s <= 1 end)
      assert.has_error(function() return s + 1 end)
      assert.has_error(function() return -s end)
      assert.has_error(function() return #s end)
      assert.has_error(function() return s.field end)
      assert.has_error(function() return s() end)
    end)

    it("is recognised by the predicates, plain values are not", function()
      assert.is_true(Safe.IsSecret(wow.secret("x")))
      assert.is_true(Safe.IsSecret(wow.secret({ 1 })))
      assert.is_true(Safe.IsSecret(wow.lock({ 1 })))
      for _, v in ipairs({ 0, "", "x", true, false, {} }) do
        assert.is_false(Safe.IsSecret(v))
      end
      assert.is_false(Safe.IsSecret(nil))
    end)
  end)

  it("Value and Bool return the not-ok form for secrets", function()
    assert.same({ nil, false }, { Safe.Value(wow.secret(1)) })
    assert.same({ 5, true }, { Safe.Value(5) })
    assert.is_nil(Safe.Bool(wow.secret(true)))
    assert.is_true(Safe.Bool(1))
    assert.is_false(Safe.Bool(nil))
    assert.is_false(Safe.Bool(false))
  end)

  it("Call fails on a missing function, an error or a secret result", function()
    assert.is_false(Safe.Call(nil))
    assert.is_false(Safe.Call(function() error("x") end))
    assert.is_false(Safe.Call(function() return 1, wow.secret(2) end))
    assert.is_false(Safe.Call(function() return wow.lock({}) end))
    assert.same({ true, 1, nil, 3 }, { Safe.Call(function(a) return a, nil, 3 end, 1) })
  end)

  it("Field and Fields refuse inaccessible tables and secret values", function()
    assert.same({ nil, false }, { Safe.Field(nil, "a") })
    assert.same({ nil, false }, { Safe.Field(wow.lock({ a = 1 }), "a") })
    assert.same({ nil, false }, { Safe.Field({ a = wow.secret(1) }, "a") })
    assert.same({ nil, true }, { Safe.Field({}, "a") })
    assert.same({ 1, true }, { Safe.Field({ a = 1 }, "a") })
    assert.same({ a = 1, b = "x" }, Safe.Fields({ a = 1, b = "x", c = wow.secret(1) }, "a", "b"))
    assert.is_nil(Safe.Fields({ a = 1, c = wow.secret(1) }, "a", "c"))
    assert.is_nil(Safe.Fields(wow.lock({ a = 1 }), "a"))
  end)

  it("Clean copies plain values only", function()
    local t = { a = 1, b = "x", c = true }
    local c = Safe.Clean(t)
    assert.same(t, c)
    assert.are_not.equal(t, c)
    assert.is_nil(Safe.Clean({ a = wow.secret(1) }))
    assert.is_nil(Safe.Clean({ a = {} }))
    assert.is_nil(Safe.Clean({ a = function() end }))
    assert.is_nil(Safe.Clean(wow.lock({ a = 1 })))
    assert.is_nil(Safe.Clean(nil))
  end)

  it("UnitName and UnitGUID return nil for secret identities", function()
    wow.unit("party1", { guid = "Player-1-00000002", name = wow.secret("Mira") })
    assert.is_nil(Safe.UnitName("party1"))
    wow.unit("party2", { guid = wow.secret("Player-1-00000003"), name = "Thalen" })
    assert.is_nil(Safe.UnitGUID("party2"))
    assert.equal("Thalen", (Safe.UnitName("party2")))
    assert.is_nil(Safe.UnitName("party4"))
  end)

  it("UnitName returns nil for the client's placeholder while a unit's name has not arrived", function()
    wow.unit("party1", { guid = "Player-1-00000002", name = "Mira", surname = "Vale", loading = true })
    assert.equal("Unknown", UnitName("party1"))
    assert.is_nil(Safe.UnitName("party1"))
    wow.unit("party2", { guid = "Player-1-00000003", name = "Unknown Being" })
    assert.is_nil(Safe.UnitName("party2"))
    wow.state.units.party1.loading = nil
    assert.same({ "Mira", "Vale", "UnitNameUnmodified" }, { Safe.UnitName("party1") })
  end)

  it("keeps the name when only the surname is secret", function()
    wow.unit("party1", { guid = "Player-1-00000002", name = "Mira", surname = wow.secret("Vale") })
    assert.same({ "Mira" }, { Safe.UnitName("party1") })
  end)

  it("reads the C_Secrets predicates through Call; nil when unknown", function()
    wow.state.identitySecret.target = true
    assert.is_true(Safe.UnitIdentityRestricted("target"))
    assert.is_false(Safe.UnitIdentityRestricted("party1"))
    wow.stub("C_Secrets.ShouldAurasBeSecret", function() error("restricted") end)
    assert.is_nil(Safe.AurasRestricted("player"))
    wow.stub("C_Secrets", nil)
    assert.is_nil(Safe.UnitIdentityRestricted("target"))
  end)

  it("InLockdown is false without the API and true when it cannot be read", function()
    assert.is_false(Safe.InLockdown())
    wow.state.chatLockdown = true
    assert.is_true(Safe.InLockdown())
    wow.stub("C_ChatInfo.InChatMessagingLockdown", function() return wow.secret(false) end)
    assert.is_true(Safe.InLockdown())
    wow.stub("C_ChatInfo.InChatMessagingLockdown", nil)
    assert.is_false(Safe.InLockdown())
  end)
end)
