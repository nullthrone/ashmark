local wow = require("tests.helpers.wow")
local mock = require("tests.helpers.campfire_mock")

local MIRA, TOBIN = "Player-1-00000002", "Player-1-00000003"

describe("Campfire", function()
  local ns, seen

  local function boot(opts)
    ns, seen = mock.boot(wow, opts)
    return ns.DB:Char()
  end

  local function rest()
    return ns.DB:Char().state.rest
  end

  before_each(function()
    wow.reset()
    wow.state.map = 1443
  end)

  after_each(function()
    assert.same({}, wow.errors)
  end)

  it("publishes the camp aura IDs at load", function()
    ns = wow.load(mock.FILES)
    assert.same({ NEARBY = 1283391, WELCOME = 1289723, BENEFITS = 1229741, BOOSTED = 1229451, BEDROLL = {} },
      ns.Campfire.AURAS)
  end)

  it("watches UNIT_AURA for the player only, and the end of combat", function()
    boot()
    assert.equal(1, ns.Events:Count("UNIT_AURA", "player"))
    assert.equal(0, ns.Events:Count("UNIT_AURA"))
    assert.is_true(ns.Events:Count("PLAYER_REGEN_ENABLED") >= 1)
  end)

  describe("a rest", function()
    it("begins when the player sits at a camp and ends with rest.camp at its benefit", function()
      local char = boot()
      assert.is_false(ns.Campfire:IsResting())
      mock.sit(wow)
      assert.same({ started = wow.state.epoch }, rest())
      assert.is_true(ns.Campfire:IsResting())
      wow.advance(60)
      mock.benefit(wow)
      assert.is_nil(rest())
      assert.equal(1, mock.count(ns, "rest.camp"))
      local entry = ns.Log:Last(char, "rest.camp")
      assert.same({ 1443, wow.state.epoch }, { entry.m, entry.t })
      assert.same({}, char.chapters)
      assert.same({}, seen.notices)
    end)

    it("ends without an entry when the player stands up before the benefit", function()
      boot()
      mock.sit(wow)
      mock.stand(wow)
      assert.is_nil(rest())
      mock.benefit(wow)
      assert.equal(0, mock.count(ns, "rest.camp"))
    end)

    it("writes nothing for a benefit that was already there, or without sitting down", function()
      boot()
      mock.benefit(wow)
      mock.aura(wow, mock.NEARBY, true)
      mock.aura(wow, mock.BOOSTED, true)
      assert.equal(0, mock.count(ns, "rest.camp"))
      mock.sit(wow)
      mock.sit(wow)
      assert.equal(0, mock.count(ns, "rest.camp"))
    end)

    it("is stale after 10 minutes: a later benefit writes nothing", function()
      boot()
      mock.sit(wow)
      wow.advance(601)
      mock.benefit(wow)
      assert.is_nil(rest())
      assert.equal(0, mock.count(ns, "rest.camp"))
    end)

    it("still counts at exactly 10 minutes", function()
      boot()
      mock.sit(wow)
      wow.advance(600)
      mock.benefit(wow)
      assert.equal(1, mock.count(ns, "rest.camp"))
    end)

    it("ignores the aura events in combat and catches up when combat ends", function()
      boot()
      wow.combat(true)
      mock.sit(wow)
      assert.is_nil(rest())
      wow.combat(false)
      assert.is_table(rest())
    end)

    it("keeps the old state while auras are restricted or a read comes back secret", function()
      boot()
      mock.sit(wow)
      wow.state.aurasSecret = true
      mock.stand(wow)
      assert.is_table(rest())
      wow.state.aurasSecret = false
      mock.aura(wow, mock.BENEFITS, wow.secret({ spellId = mock.BENEFITS }))
      assert.is_table(rest())
      assert.equal(0, mock.count(ns, "rest.camp"))
      mock.benefit(wow)
      assert.equal(1, mock.count(ns, "rest.camp"))
    end)
  end)

  describe("chapter check", function()
    it("closes the chapter at 20 entries with the party, the notice and the page-turn sound", function()
      wow.unit("party2", { guid = TOBIN, name = "Tobin" })
      wow.unit("party1", { guid = MIRA, name = "Mira" })
      local char = boot()
      mock.fillTo(ns, 19)
      mock.sit(wow)
      wow.sounds = {}
      mock.benefit(wow)
      assert.equal(1, #char.chapters)
      assert.same({ no = 1, from = 1, to = 21 }, { no = char.chapters[1].no, from = char.chapters[1].from,
                                                 to = char.chapters[1].to })
      assert.same({ "rest.camp", "chapter" }, { char.log[20].k, char.log[21].k })
      assert.same({ MIRA, TOBIN }, seen.chapters[1].members)
      assert.same({ "Chapter I closes · Desolace" }, seen.notices)
      assert.equal("Chapter I closes · Desolace", _G.AshmarkNoticeFrame.Text:GetText())
      assert.same({ SOUNDKIT.IG_ABILITY_PAGE_TURN }, wow.sounds)
    end)

    it("leaves a chapter of 19 entries open", function()
      local char = boot()
      mock.fillTo(ns, 18)
      mock.sit(wow)
      mock.benefit(wow)
      assert.same({}, char.chapters)
      assert.same({}, seen.notices)
    end)

    it("counts only the entries since the last chapter", function()
      local char = boot()
      mock.fill(ns, 30)
      ns.Log:CloseChapter({})
      mock.fill(ns, 10)
      mock.sit(wow)
      mock.benefit(wow)
      assert.equal(1, #char.chapters)
    end)

    it("closes a chapter whose first entry is 30 minutes old", function()
      local char = boot()
      ns.Log:Add("level", { l = 2 })
      wow.advance(1740)
      mock.sit(wow)
      wow.advance(60)
      mock.benefit(wow)
      assert.equal(1, #char.chapters)
      assert.same({}, seen.chapters[1].members)
      assert.same({ "Chapter I closes · Desolace" }, seen.notices)
    end)

    it("leaves a younger chapter open", function()
      local char = boot()
      ns.Log:Add("level", { l = 2 })
      wow.advance(1739)
      mock.sit(wow)
      wow.advance(60)
      mock.benefit(wow)
      assert.same({}, char.chapters)
    end)

    it("plays no sound with Core.sounds off and names an unknown place", function()
      wow.state.map = nil
      boot()
      mock.fillTo(ns, 19)
      ns.Settings:Set("Core.sounds", false)
      wow.sounds = {}
      mock.sit(wow)
      mock.benefit(wow)
      assert.same({ "Chapter I closes · " .. ns.L.CORE_UNKNOWN_PLACE }, seen.notices)
      assert.same({}, wow.sounds)
    end)
  end)

  describe("bedroll", function()
    local function withBedroll()
      return boot({ setup = function(loaded) loaded.Campfire.AURAS.BEDROLL = { 555, 556 } end })
    end

    it("writes rest.bedroll when a bedroll aura appears and checks the chapter", function()
      local char = withBedroll()
      mock.fillTo(ns, 19)
      mock.aura(wow, 556, true)
      assert.equal(1, mock.count(ns, "rest.bedroll"))
      assert.equal(1, #char.chapters)
      mock.aura(wow, 556, nil)
      mock.aura(wow, 555, true)
      assert.equal(2, mock.count(ns, "rest.bedroll"))
      assert.equal(1, #char.chapters)
    end)

    it("counts a bedroll aura that replaces or joins another as the same rest", function()
      withBedroll()
      mock.aura(wow, 556, true)
      mock.aura(wow, 555, true)
      assert.equal(1, mock.count(ns, "rest.bedroll"))
      mock.aura(wow, 555, nil, true)
      mock.aura(wow, 556, nil)
      mock.aura(wow, 555, true)
      assert.equal(2, mock.count(ns, "rest.bedroll"))
      mock.aura(wow, 556, true, true)
      mock.aura(wow, 555, nil)
      assert.equal(2, mock.count(ns, "rest.bedroll"))
    end)

    it("writes one entry when two bedroll auras appear at once", function()
      withBedroll()
      mock.aura(wow, 555, true, true)
      mock.aura(wow, 556, true)
      assert.equal(1, mock.count(ns, "rest.bedroll"))
    end)
  end)

  describe("after a reload", function()
    it("seeds the auras at a camp and writes nothing", function()
      local char = boot()
      mock.fill(ns, 25)
      mock.sit(wow)
      mock.benefit(wow)
      local seq = ns.Log:Seq(char)
      ns = wow.reload()
      assert.equal(seq, ns.Log:Seq(ns.DB:Char()))
      wow.fire("UNIT_AURA", "player")
      assert.equal(seq, ns.Log:Seq(ns.DB:Char()))
    end)

    it("keeps a rest while the player still sits, so the benefit after the reload counts", function()
      boot()
      mock.sit(wow)
      local started = rest().started
      ns = wow.reload()
      assert.same({ started = started }, ns.DB:Char().state.rest)
      mock.benefit(wow)
      assert.equal(1, mock.count(ns, "rest.camp"))
    end)

    it("drops a rest when the player no longer sits", function()
      boot()
      mock.sit(wow)
      mock.aura(wow, mock.WELCOME, nil, true)
      ns = wow.reload()
      assert.is_nil(ns.DB:Char().state.rest)
      mock.benefit(wow)
      assert.equal(0, mock.count(ns, "rest.camp"))
    end)

    it("seeds on the first complete read when the reload came in combat", function()
      boot()
      mock.sit(wow)
      mock.benefit(wow)
      local seq = ns.Log:Seq(ns.DB:Char())
      wow.state.combatLockdown = true
      ns = wow.reload()
      wow.combat(false)
      assert.equal(seq, ns.Log:Seq(ns.DB:Char()))
      assert.is_true(ns.Campfire:IsResting())
    end)
  end)

  describe("IsResting", function()
    it("is a rest at most 10 minutes old, or sitting at a camp", function()
      local char = boot()
      local now = wow.state.epoch
      char.state.rest = { started = now - 600 }
      assert.is_true(ns.Campfire:IsResting())
      char.state.rest = { started = now - 601 }
      assert.is_false(ns.Campfire:IsResting())
      mock.aura(wow, mock.WELCOME, true)
      char.state.rest = nil
      assert.is_true(ns.Campfire:IsResting())
    end)

    it("answers while the module is off or unavailable", function()
      wow.stub("C_UnitAuras.GetPlayerAuraBySpellID", nil)
      local char = boot()
      assert.same({ "auras" }, ns.Campfire.unavailable)
      assert.is_false(ns.Campfire:IsResting())
      char.state.rest = { started = wow.state.epoch }
      assert.is_true(ns.Campfire:IsResting())
    end)
  end)

  it("does nothing while the module is off and seeds again when it comes back", function()
    boot()
    mock.sit(wow)
    ns.Settings:Set("Campfire.enabled", false)
    assert.equal(0, ns.Events:Count("UNIT_AURA", "player"))
    mock.benefit(wow)
    assert.equal(0, mock.count(ns, "rest.camp"))
    ns.Settings:Set("Campfire.enabled", true)
    assert.is_table(rest())
    assert.equal(0, mock.count(ns, "rest.camp"))
    mock.stand(wow)
    assert.is_nil(rest())
  end)

  describe("test checks", function()
    it("resolve every aura ID to a spell name", function()
      boot({ setup = function(loaded) loaded.Campfire.AURAS.BEDROLL = { 555 } end })
      for id, name in pairs({ [1283391] = "Campfire", [1289723] = "Welcoming", [1229741] = "Camp Benefits",
                              [1229451] = "Boosted Rest", [555] = "Well-Rested" }) do
        wow.data.spells[id] = name
      end
      local ok, detail = mock.check(ns, "Campfire.auras")
      assert.is_true(ok)
      assert.equal("NEARBY 1283391 Campfire, WELCOME 1289723 Welcoming, BENEFITS 1229741 Camp Benefits, "
        .. "BOOSTED 1229451 Boosted Rest, BEDROLL 555 Well-Rested", detail)
      wow.data.spells[1229741] = nil
      ok, detail = mock.check(ns, "Campfire.auras")
      assert.is_false(ok)
      assert.truthy(detail:find("unresolved: BENEFITS 1229741", 1, true))
    end)

    it("note an empty bedroll list and skip without C_Spell.GetSpellName", function()
      boot()
      for _, id in ipairs({ 1283391, 1289723, 1229741, 1229451 }) do wow.data.spells[id] = "x" end
      local ok, detail = mock.check(ns, "Campfire.auras")
      assert.is_true(ok)
      assert.truthy(detail:find("BEDROLL none verified", 1, true))
      wow.stub("C_Spell.GetSpellName", nil)
      assert.is_nil((mock.check(ns, "Campfire.auras")))
    end)

    it("report the present state and the rest", function()
      boot()
      mock.sit(wow)
      wow.advance(30)
      local ok, detail = mock.check(ns, "Campfire.present")
      assert.is_true(ok)
      assert.equal("NEARBY=false, WELCOME=true, BENEFITS=false, BOOSTED=false, rest 30 s, resting true", detail)
      ns.Settings:Set("Campfire.enabled", false)
      assert.same({ nil, "off" }, { mock.check(ns, "Campfire.present") })
    end)

    it("fail when the module is unavailable", function()
      wow.stub("C_UnitAuras.GetPlayerAuraBySpellID", nil)
      boot()
      assert.same({ false, "unavailable: auras" }, { mock.check(ns, "Campfire.present") })
    end)
  end)
end)
